#!/usr/bin/env python3
"""CR-IS-CAT-01C-P5 deterministic relationship-registry population generator.

Emits the P5 registry block into relationships/v1-alpha/relationships.yaml:

1. One dea:executes edge per CR-IS-CAT-01C-P4 function record (594 records),
   derived from each record's executing_components allocation (evidence-driven
   per G-09; no discretionary selection).
2. One dea:measured_by edge per CR-IS-CAT-01C-P4 function record, resolved
   through the curated system-archetype to anchor-metric bridge in
   scripts/p5_registry_data.json (34 vendor-neutral archetypes, one anchor
   metric each from the vendored dea-catalog-metrics snapshot; per G-11 the
   measured_by row is an OpenDEAM v0.7.0 allocation declaration, not a
   metamodel relationship claim, and the metric definition remains owned by
   the Metric catalogue).

Also appends the P5 change_history entry. The generator is idempotent per
G-10: existing P5 blocks are stripped before regeneration, so re-running
reproduces the file byte-identically.

Usage: python3 scripts/generate_p5_registry.py
"""
from __future__ import annotations

import json
import os
import re
import sys

import yaml

WORKDIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(WORKDIR)

REGISTRY_PATH = 'relationships/v1-alpha/relationships.yaml'
DATA_PATH = 'scripts/p5_registry_data.json'
P4_DATA_PATH = 'scripts/p4_function_data.json'
SNAPSHOT_PATH = 'docs/is-semantic-architecture/target-id-snapshots.yaml'

CR = 'CR-IS-CAT-01C-P5'
DATE = '2026-11-12'

BLOCK_BEGIN = ('# ---- CR-IS-CAT-01C-P5 registry population (begin; generated by '
               'scripts/generate_p5_registry.py; do not edit) ----')
BLOCK_END = '# ---- CR-IS-CAT-01C-P5 registry population (end) ----'
HISTORY_BEGIN = ('# ---- CR-IS-CAT-01C-P5 change history (begin; generated by '
                 'scripts/generate_p5_registry.py; do not edit) ----')
HISTORY_END = '# ---- CR-IS-CAT-01C-P5 change history (end) ----'

FUNCTION_PREFIX = 'dea:information-system-function-'
COMPONENT_PREFIX = 'dea:information-system-component-'
METRIC_PREFIX = 'dea:metric-'

# D-004 / D-005 glyph and punctuation embargo.
EMBARGO = [u'\u2014', u'\u2013', u'\u2026', ';' * 3]


def assert_embargo(text, where):
    for glyph in EMBARGO:
        if glyph in text:
            raise SystemExit(f'EMBARGO violation ({where}): {glyph!r} found')


def yscalar(value):
    """Minimal deterministic YAML scalar emission.

    Plain style unless the value contains a character that would change YAML
    parsing (':' followed by space or EOL, ' #' inside, leading/trailing
    whitespace, leading indicator characters), in which case single-quoted
    style with '' escaping is used.
    """
    s = str(value)
    assert_embargo(s, 'scalar')
    needs_quotes = (
        s == '' or s != s.strip()
        or re.search(r':(\s|$)', s)
        or ' #' in s
        or s[0] in '&*!|>%@`{}[],"\'' + '-?'
    )
    if needs_quotes:
        return "'" + s.replace("'", "''") + "'"
    return s


def load_p4_functions():
    """All CR-IS-CAT-01C-P4 function records with their evidence crawl."""
    import glob
    functions = []
    for f in sorted(glob.glob('entities/v1-alpha/domains/*/functions/*/function.yaml')):
        with open(f) as fp:
            d = yaml.safe_load(fp)
        if (d.get('metadata') or {}).get('cr') == 'CR-IS-CAT-01C-P4':
            comps = d.get('executing_components') or []
            if len(comps) != 1:
                raise SystemExit(
                    f'{d["id"]}: expected exactly 1 executing component, found {len(comps)}')
            functions.append({
                'id': d['id'],
                'name': d['name'],
                'component': comps[0],
            })
    if not functions:
        raise SystemExit('no CR-IS-CAT-01C-P4 function records found')
    return functions


def load_system_map():
    """Function id -> vendor-neutral system archetype (from the P4 data file)."""
    with open(P4_DATA_PATH) as fp:
        p4 = json.load(fp)
    return {f['id']: f['system'] for f in p4['functions']}


def load_bridge():
    with open(DATA_PATH) as fp:
        data = json.load(fp)
    bridge = {row['system']: row for row in data['system_anchor_metrics']}
    if len(bridge) != len(data['system_anchor_metrics']):
        raise SystemExit('duplicate system keys in p5_registry_data.json')
    return data, bridge


def load_snapshot_ids():
    with open(SNAPSHOT_PATH) as fp:
        snap = yaml.safe_load(fp)
    return {
        repo: set(ids)
        for repo, ids in (snap.get('snapshots') or {}).items()
    }


def emit_relationship(rel):
    lines = [
        f"- id: {rel['id']}",
        f"  source_id: {rel['source_id']}",
        f"  relationship_type: {rel['relationship_type']}",
        f"  target_id: {rel['target_id']}",
        f"  relationship_description: {yscalar(rel['relationship_description'])}",
        f"  provenance: {yscalar(rel['provenance'])}",
        f"  validity_status: {rel['validity_status']}",
        f"  effective_version: '{rel['effective_version']}'",
        f"  evidence: {yscalar(rel['evidence'])}",
        '  metadata: {}',
    ]
    return '\n'.join(lines)


def build_p5_block(functions, bridge, snapshot_ids):
    """Emit the P5 registry block: executes + measured_by per function."""
    isc_ids = snapshot_ids.get('dea-catalog-application-components', set())
    metric_ids = snapshot_ids.get('dea-catalog-metrics', set())

    entries = []
    seen_ids = set()
    for fn in sorted(functions, key=lambda x: x['id']):
        fn_slug = fn['id'][len(FUNCTION_PREFIX):]
        assert fn['component'].startswith(COMPONENT_PREFIX), fn['component']
        comp_slug = fn['component'][len(COMPONENT_PREFIX):]

        # dea:executes (function executed by its P4 executing component).
        exec_id = f'rel:{fn_slug}-executes-{comp_slug}'
        entries.append({
            'id': exec_id,
            'source_id': fn['id'],
            'relationship_type': 'dea:executes',
            'target_id': fn['component'],
            'relationship_description': (
                f"The {fn['name']} function is executed by the {comp_slug} component "
                '(per the CR-IS-CAT-01C-P4 executing_components allocation).'),
            'provenance': (
                f'{CR} registry population ({DATE}); executing_components '
                'allocation from CR-IS-CAT-01C-P4'),
            'validity_status': 'planned',
            'effective_version': '1.0',
            'evidence': 'CR-IS-CAT-01C-P4 function record executing_components '
                        '(vendor-neutral; per G-12 no vendor product is canonical)',
        })
        if fn['component'] not in isc_ids:
            raise SystemExit(f'{exec_id}: target missing from ISC snapshot: {fn["component"]}')

        # dea:measured_by (system anchor metric allocation, G-11).
        system = SYSTEM_MAP.get(fn['id'])
        if system is None:
            raise SystemExit(f'{fn["id"]}: no system archetype in {P4_DATA_PATH}')
        row = bridge.get(system)
        if row is None:
            raise SystemExit(f'{fn["id"]}: no anchor metric for system archetype: {system}')
        metric_slug = row['metric_id'][len(METRIC_PREFIX):]
        mb_id = f'rel:{fn_slug}-measured-by-{metric_slug}'
        entries.append({
            'id': mb_id,
            'source_id': fn['id'],
            'relationship_type': 'dea:measured_by',
            'target_id': row['metric_id'],
            'relationship_description': (
                f"The {fn['name']} function is measured by the {row['metric_name']} metric "
                f'(per the OpenDEAM v0.7.0 measured_by:[MTR] allocation; {system} '
                'system anchor metric).'),
            'provenance': (
                f'{CR} registry population ({DATE}); system anchor metric bridge '
                'from scripts/p5_registry_data.json'),
            'validity_status': 'planned',
            'effective_version': '1.0',
            'evidence': (
                'OpenDEAM v0.7.0 measured_by:[MTR]; anchor metric record '
                f'{row["metric_id"]} in dea-catalog-metrics ({row["metric_domain"]}); '
                'per G-11 the metric definition remains owned by the Metric catalogue'),
        })
        if row['metric_id'] not in metric_ids:
            raise SystemExit(f'{mb_id}: target missing from metrics snapshot: {row["metric_id"]}')

        for e in entries[-2:]:
            if e['id'] in seen_ids:
                raise SystemExit(f'duplicate relationship id: {e["id"]}')
            seen_ids.add(e['id'])
            assert_embargo(e['id'] + e['relationship_description'] + e['evidence'], e['id'])

    header = (
        f'{BLOCK_BEGIN}\n'
        f'# {CR} registry population. One dea:executes edge per CR-IS-CAT-01C-P4\n'
        f'# function (from its executing_components evidence) and one\n'
        f'# dea:measured_by edge per function (system anchor metric bridge,\n'
        f'# scripts/p5_registry_data.json; G-11 allocation declaration).')
    body = '\n'.join(emit_relationship(e) for e in entries)
    block = f'{header}\n{body}\n{BLOCK_END}'
    return block, entries


def strip_block(text, begin_marker, end_marker):
    """Remove a marked generated block (idempotency; per G-10)."""
    pattern = re.compile(
        re.escape(begin_marker) + r'.*?' + re.escape(end_marker) + r'\n?',
        re.DOTALL)
    return pattern.sub('', text)


def main():
    global SYSTEM_MAP
    functions = load_p4_functions()
    SYSTEM_MAP = load_system_map()
    data, bridge = load_bridge()
    snapshot_ids = load_snapshot_ids()

    block, entries = build_p5_block(functions, bridge, snapshot_ids)

    with open(REGISTRY_PATH) as fp:
        text = fp.read()

    # Idempotent strip of previous P5 population (G-10).
    text = strip_block(text, BLOCK_BEGIN, BLOCK_END)
    text = strip_block(text, HISTORY_BEGIN, HISTORY_END)

    # Insert the P5 block at the end of the relationships list (before
    # change_history:).
    anchor = 'change_history:'
    idx = text.index(anchor)
    if idx == -1:
        raise SystemExit('change_history: not found in registry')
    text = text[:idx] + block + '\n' + text[idx:]

    # Append the P5 change_history entry (marked block).
    note = (
        f"P5 registry population. {len(entries)} relationship records "
        f"({len(functions)} dea:executes edges from the CR-IS-CAT-01C-P4 "
        f"executing_components evidence and {len(functions)} dea:measured_by "
        f"edges via the 34-row system anchor metric bridge, "
        f"scripts/p5_registry_data.json). Target-id snapshots re-pinned: "
        f"dea-catalog-application-components at "
        f"{data['pins']['dea-catalog-application-components'][:12]} (735 ids, "
        f"includes the CR-IS-CAT-02C-P5 F3 atoms) and dea-catalog-metrics at "
        f"{data['pins']['dea-catalog-metrics'][:12]} (4433 ids, new target "
        f"catalogue). Per G-11 the measured_by rows are OpenDEAM allocation "
        f"declarations, not metamodel relationship claims.")
    history = (
        f'{HISTORY_BEGIN}\n'
        f"- version: '1.1'\n"
        f"  date: {DATE}\n"
        f"  cr: {CR}\n"
        f"  note: {yscalar(note)}\n"
        f'{HISTORY_END}\n')
    text = text.rstrip('\n') + '\n' + history

    with open(REGISTRY_PATH, 'w') as fp:
        fp.write(text)

    # Parse-back verification of the full registry.
    doc = yaml.safe_load(open(REGISTRY_PATH))
    rels = doc['relationships']
    ids = [r['id'] for r in rels]
    if len(ids) != len(set(ids)):
        raise SystemExit('duplicate relationship ids after merge')
    print(f'OK: {REGISTRY_PATH}')
    print(f'  P5 entries : {len(entries)} '
          f'({len(functions)} executes + {len(functions)} measured_by)')
    print(f'  registry    : {len(rels)} total relationship records')


if __name__ == '__main__':
    main()
